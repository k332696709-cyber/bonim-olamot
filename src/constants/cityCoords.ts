const norm = (s: string) =>
  s.replace(/\([^)]*\)/g, ' ').replace(/[״"׳']/g, '').replace(/קריית/g, 'קרית').replace(/[-־–]/g, ' ').replace(/\s+/g, ' ').trim()

const TABLE = Object.entries(RAW)
  .map(([k, v]) => [norm(k), v] as [string, [number, number]])
  .sort((a, b) => b[0].length - a[0].length) // longest name first, so "קרית שמונה" wins over shorter parts

/** Coordinates for a city name as written in the registration or in a date-spot's city label. */
export function cityCoords(name: string | null | undefined): [number, number] | null {
  const n = norm(name ?? '')
  if (!n) return null
  for (const [k, v] of TABLE) if (k === n) return v
  for (const [k, v] of TABLE) if (n.includes(k)) return v
  return null
}

/** Distance in kilometres between two points on the earth. */
export function distanceKm(a: [number, number], b: [number, number]): number {
  const rad = (d: number) => (d * Math.PI) / 180
  const dLat = rad(b[0] - a[0])
  const dLng = rad(b[1] - a[1])
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a[0])) * Math.cos(rad(b[0])) * Math.sin(dLng / 2) ** 2
  return 2 * 6371 * Math.asin(Math.sqrt(h))
}
